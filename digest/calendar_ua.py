def orthodox_easter(year: int) -> date:
    """Великдень за юліанською пасхалією (ПЦУ), у григоріанських датах (для 1900–2099)."""
    a, b, c = year % 4, year % 7, year % 19
    d = (19 * c + 15) % 30
    e = (2 * a + 4 * b - d + 34) % 7
    n = d + e + 114
    return date(year, n // 31, n % 31 + 1) + timedelta(days=13)


def nth_weekday(year: int, month: int, weekday: int, n: int) -> date:
    """n-й (1..) день тижня (0=пн) у місяці; n=-1 — останній."""
    if n > 0:
        d = date(year, month, 1)
        d += timedelta(days=(weekday - d.weekday()) % 7 + 7 * (n - 1))
        return d
    d = date(year + (month == 12), month % 12 + 1, 1) - timedelta(days=1)
    return d - timedelta(days=(d.weekday() - weekday) % 7)


